//! The fixture tree must contain nothing git does not know about.
//!
//! `750f5fb` committed 36 test-generated copies because they were staged with `git add -A`.
//! Nothing noticed for two commits, and nothing could: the copies are created by
//! `std::fs::copy` beside a real fixture, they are byte-identical to an input, and their
//! cleanup is `let _ = std::fs::remove_file(...)` on success paths only — so an aborted or
//! panicking run leaves them behind and the suite still reports a pass. `.gitignore` covers
//! the two prefixes that run produced (`sample-*`, `docreader-stress-*`). That is a backstop
//! for two names, not a guarantee: a test that writes next to its input under a new name
//! recreates the hazard, and a stray file is indistinguishable from an input on inspection.
//!
//! The property is about *untracked* files and deliberately not about modified ones. Mid-task
//! a tracked fixture is routinely regenerated by `examples/make_p24_fixtures`; failing on that
//! would make this guard fire on correct work and teach the next person to disable it. The
//! hazard is a file git has never heard of, so the query is `git ls-files --others
//! --exclude-standard`.

use std::path::{Path, PathBuf};

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("src-tauri must have a parent directory")
        .to_path_buf()
}

fn fixtures_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures")
}

/// Measured at this commit: 52 `.pdf` + `README.md` + `sample.txt`. A floor rather than an
/// equality because the property is "the enumeration is not blind", not "no fixture was
/// added" — a new fixture must not have to edit this number. It sits at the measured value
/// with no headroom, so lowering it is caught.
const FIXTURE_FLOOR: usize = 54;

/// Every regular file below `dir`, recursively.
fn regular_files(dir: &Path) -> Vec<PathBuf> {
    let mut found = Vec::new();
    let entries =
        std::fs::read_dir(dir).unwrap_or_else(|e| panic!("cannot read {}: {e}", dir.display()));
    for entry in entries.flatten() {
        let path = entry.path();
        match entry.file_type() {
            Ok(kind) if kind.is_dir() => found.extend(regular_files(&path)),
            Ok(kind) if kind.is_file() => found.push(path),
            _ => {}
        }
    }
    found.sort();
    found
}

/// Splits `git ls-files -z` output. It must be on NUL and only on NUL: a filename may contain
/// a newline, and the earlier draft of this guard split the *newline*-separated output on NUL
/// and reported 54 paths as **one** entry. That is the failure this helper's own test pins.
fn paths_from_nul_output(raw: &[u8]) -> Vec<String> {
    raw.split(|byte| *byte == 0)
        .filter(|field| !field.is_empty())
        .map(|field| String::from_utf8_lossy(field).into_owned())
        .collect()
}

fn git(root: &Path, args: &[&str]) -> Vec<u8> {
    let output = std::process::Command::new("git")
        .args(args)
        .current_dir(root)
        .output()
        .unwrap_or_else(|e| panic!("git must be available to check the fixture tree: {e}"));
    assert!(
        output.status.success(),
        "`git {}` failed: {}",
        args.join(" "),
        String::from_utf8_lossy(&output.stderr)
    );
    output.stdout
}

#[test]
fn the_untracked_reader_splits_on_nul_and_not_on_newlines() {
    // The defect shape: a path containing a newline. A newline splitter returns two entries
    // where git reported one, and a guard fed such a path would name a file that does not
    // exist while missing the one that does. This is the sample that fails on the broken
    // parser rather than on the tree.
    let embedded = b"src-tauri/tests/fixtures/odd\nname.pdf\0src-tauri/tests/fixtures/b.pdf\0";
    assert_eq!(
        paths_from_nul_output(embedded),
        vec![
            "src-tauri/tests/fixtures/odd\nname.pdf".to_string(),
            "src-tauri/tests/fixtures/b.pdf".to_string()
        ],
        "the splitter must be NUL-only, so a newline inside a path stays inside it"
    );

    // The other defect shape, measured on the first draft of this guard: `git ls-files` run
    // without `-z` emits newlines, and a NUL splitter then reports the whole listing as one
    // entry -- 54 paths arriving as 1. The reader cannot detect that, which is why the caller
    // asserts a count floor as well.
    assert_eq!(
        paths_from_nul_output(b"a.pdf\nb.pdf\n"),
        vec!["a.pdf\nb.pdf\n".to_string()],
        "newline-separated input is one NUL record; the floor assertion in the caller is what \
         turns this into a loud failure"
    );

    // git terminates the last record with NUL, so a trailing empty field is normal and must
    // not be reported as a path.
    assert_eq!(paths_from_nul_output(b"one\0"), vec!["one".to_string()]);
    assert!(paths_from_nul_output(b"").is_empty());
}

#[test]
fn the_fixture_tree_holds_no_untracked_files() {
    let root = repo_root();
    let dir = fixtures_dir();

    let on_disk = regular_files(&dir);
    assert!(
        on_disk.len() >= FIXTURE_FLOOR,
        "enumerated only {} files under tests/fixtures/, expected at least {FIXTURE_FLOOR}; \
         the guard is blind and a stray would pass",
        on_disk.len()
    );

    // Precondition on the *other* query too: if the pathspec were wrong, the untracked list
    // below would be empty for the wrong reason. Both counts are read from the same tree.
    let tracked = paths_from_nul_output(&git(
        &root,
        &["ls-files", "-z", "--", "src-tauri/tests/fixtures"],
    ));
    assert!(
        tracked.len() >= FIXTURE_FLOOR,
        "git reported only {} tracked files under tests/fixtures/, expected at least \
         {FIXTURE_FLOOR}; the pathspec or the reader is wrong and the check would pass \
         vacuously",
        tracked.len()
    );

    let untracked = paths_from_nul_output(&git(
        &root,
        &[
            "ls-files",
            "--others",
            "--exclude-standard",
            "-z",
            "--",
            "src-tauri/tests/fixtures",
        ],
    ));

    assert!(
        untracked.is_empty(),
        "untracked files under tests/fixtures/: {untracked:?}\n\
         A concurrency test's leftover copy, or a stray swept in by `git add -A`, is \
         byte-identical to an input and cannot be told apart by inspection. Delete it, or \
         commit it deliberately by explicit path. Note the limit of this guard: \
         `--exclude-standard` hides anything matching .gitignore, so it cannot see a stray \
         named `sample-*.pdf` or `docreader-stress-*.pdf`."
    );
}
