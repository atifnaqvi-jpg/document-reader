//! PFX / PKCS#12 import (D-SG5, D-SG1 as amended 2026-11-08).
//!
//! The password arrives through the [`PasswordStore`] closure, never as a value this module can
//! hold: `import_with_store` takes the store and the key, and the plaintext exists only inside the
//! closure that hands it to the archive reader.
//!
//! **The dependency boundary is a property of this file.** `p12-keystore` is the PFX reader because
//! `pkcs12` cannot decrypt a PFX at all (design K22). K24 predicts that this choice costs a second
//! `der` generation in the lock file; measured today it costs none, because `rsa` -- the crate that
//! would bring `der 0.7` -- is not in the lock yet. K25 bounds the cost when it arrives: this crate
//! parses and decrypts, and nothing else. Every type that leaves this module is a `Vec<u8>` of DER, so a `der 0.8` type
//! cannot reach the signing path, the CMS builder, the database or the UI. That boundary is
//! asserted by a source scan in `tests/signing_surface.rs` rather than trusted as a convention.
//!
//! What this module does **not** claim: that the certificate is trusted. Import proves the archive
//! opened with the password that sealed it. Trust is D-SG4's separate question and this module has
//! no opinion about it.

use std::path::Path;

use p12_keystore::{KeyStore, KeyStoreEntry, Pkcs12ImportPolicy};

use crate::editor::session::PasswordStore;
use crate::model::AppError;

/// One imported identity: a private key and the certificate chain that goes with it.
///
/// DER, not the reader's own types (K25). `chain[0]` is the entity certificate and the last entry,
/// when the chain is longer than one, is the root the archive shipped. An archive is not obliged to
/// include a root; a one-entry chain is legal and is what a self-signed signer produces.
#[derive(Clone, PartialEq, Eq)]
pub struct ImportedIdentity {
    pub alias: String,
    pub key_der: Vec<u8>,
    pub chain: Vec<Vec<u8>>,
}

impl std::fmt::Debug for ImportedIdentity {
    /// Prints the alias and the chain length, never the key.
    ///
    /// The key is not secret in the sense a password is — it arrived already decrypted and the
    /// password that protected it is gone — but `Debug` is the usual accidental exit for private
    /// bytes: a panic message, an `assert_eq!` failure, a log line. Redacting costs nothing.
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("ImportedIdentity")
            .field("alias", &self.alias)
            .field("key_der", &"<redacted>")
            .field("chain_len", &self.chain.len())
            .finish()
    }
}

/// Everything a PFX yielded.
///
/// Certificates that carry no private key come back separately: a PFX may ship a trust anchor on
/// its own, and silently dropping it would narrow the chain the user is able to build.
#[derive(Debug, Default)]
pub struct ImportedPfx {
    pub identities: Vec<ImportedIdentity>,
    /// DER certificates that arrived without a key, offered as an extra chain by the signer.
    ///
    /// **Collected but unexercised.** Under `Strict` a certificate is kept on its own only when it
    /// is marked trusted, and no fixture generated by `openssl pkcs12 -nokeys` (with or without
    /// `-addtrust`) reaches that state. Dropping the field instead would silently discard a trust
    /// anchor a real archived PFX may carry, so it is kept and this note records that its
    /// population is untested rather than implying coverage.
    pub extra_certificates: Vec<Vec<u8>>,
}

/// Read a PFX from bytes with an explicit password.
///
/// The low-level entry point, public for tests and for a caller holding a password from somewhere
/// other than the store. [`import_with_store`] is what the app should use.
pub fn import_bytes(bytes: &[u8], password: &str) -> Result<ImportedPfx, AppError> {
    // `Strict` links each key to its certificate by local key id, and *drops* whatever does not
    // link -- a key with no matching certificate, a certificate that is neither trusted nor
    // attached. Dropping is the filter a signer wants, because an unmatched key cannot sign. It is
    // also silent, which is why the emptiness check at the end of this function exists: filtering
    // is not the same as reporting. `Relaxed` was measured to behave identically on this fixture,
    // so it is not an alternative worth carrying.
    let store = KeyStore::from_pkcs12(bytes, password, Pkcs12ImportPolicy::Strict)
        .map_err(|error| map_import_error(&error))?;

    let mut imported = ImportedPfx::default();
    for (alias, entry) in store.entries() {
        match entry {
            KeyStoreEntry::PrivateKeyChain(chain) => {
                imported.identities.push(ImportedIdentity {
                    alias: alias.clone(),
                    key_der: chain.key().as_der().to_vec(),
                    chain: chain
                        .certs()
                        .iter()
                        .map(|certificate| certificate.as_der().to_vec())
                        .collect(),
                });
            }
            KeyStoreEntry::Certificate(certificate) => {
                imported
                    .extra_certificates
                    .push(certificate.as_der().to_vec());
            }
            // A secret bag is neither a certificate nor a key. Ignoring it is the honest choice:
            // this build has no use for one, and inventing a use would be scope creep.
            KeyStoreEntry::Secret(_) => {}
        }
    }

    // `Strict` drops a key that matches no certificate, and drops a certificate that is neither
    // trusted nor attached to a key. Both are right for a signer -- neither artefact can sign --
    // but together they let a whole archive reduce to nothing while still reporting success.
    // Measured: a PFX exported with `-nocerts` opens cleanly and yields zero entries, so the caller
    // would show an empty list and no reason for it. That is the silent skip this codebase forbids,
    // so emptiness is a named outcome.
    //
    // One message, not two. A variant that reported the certificate count was written first and then
    // deleted: no fixture this build can generate reaches that branch, because `Strict` keeps a
    // certificate on its own only when it is marked trusted, and neither `openssl -nokeys` nor
    // `-addtrust` produced one the reader treated as such. An unexercised message is a claim.
    if imported.identities.is_empty() {
        return Err(AppError::PfxInvalid(
            "this keystore opened, but holds no private key with a matching certificate; a \
             keystore that can sign must contain both"
                .to_string(),
        ));
    }
    Ok(imported)
}

/// Read a PFX from a file, taking the password from the [`PasswordStore`] if it holds one.
///
/// The key is the *PFX's* path, which is what the store is keyed by: a keystore file the user
/// imported once and may reuse across documents. Returns `Ok(None)` when no password is held, so
/// the caller can prompt rather than guess.
pub fn import_with_store(
    store: &PasswordStore,
    path: &Path,
) -> Result<Option<ImportedPfx>, AppError> {
    let key = path.to_string_lossy();
    let bytes = std::fs::read(path)
        .map_err(|error| AppError::Other(format!("could not read {}: {error}", path.display())))?;
    store
        .with_password(&key, |password| import_bytes(&bytes, password))
        .transpose()
}

/// Map the reader's errors onto ours, and **do not** forward its text for the password case.
///
/// The distinction the user needs is fixed: "that password did not open this file" versus "this
/// file is not a PFX". Collapsing them sends someone hunting for a corrupt download when they
/// mistyped. Forwarding the library's message would also risk quoting archive contents into a UI
/// string, so the password case gets our own wording and only the remaining cases keep the detail.
///
/// Matched on the **typed** variant, not on the message text. An earlier version tested
/// `message.contains("MAC tag mismatch")`, which works today and silently mislabels every wrong
/// password the day the dependency rewords that sentence — a wrong-diagnosis bug that would pass
/// review because the test fixture would still fail, just with the wrong error.
fn map_import_error(error: &p12_keystore::error::Error) -> AppError {
    use p12_keystore::error::Error;
    match error {
        // A failed MAC is what a wrong password produces. The reader cannot tell that apart from a
        // corrupt archive, because both make the MAC disagree, so the message names both —
        // reporting it as a corrupt file would be a lie in the common case, and vice versa.
        Error::MacError(_) => AppError::PfxPasswordOrDamaged,
        // A truncated or non-PFX file fails earlier, in parsing, and `DerError` carries the reason.
        other => AppError::PfxInvalid(other.to_string()),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A real PFX from `openssl pkcs12 -export` with AES-256-CBC for both bags and a SHA-256 MAC,
    /// i.e. the PBES2/PBKDF2 shape OpenSSL 3.0 produces by default. Embedded so the test needs
    /// neither `openssl` nor network at run time; `tests/fixtures/signing/README.md` records what
    /// it is and why a private key is committed.
    const SIGNER_PFX: &[u8] = include_bytes!("../../../tests/fixtures/signing/signer.pfx");
    const SIGNER_PASSWORD: &str = "correct-horse";

    #[test]
    fn a_real_pfx_imports_one_identity_with_its_certificate() {
        let imported = import_bytes(SIGNER_PFX, SIGNER_PASSWORD).expect("the archive must open");
        assert_eq!(imported.identities.len(), 1, "one keychain");
        let identity = &imported.identities[0];
        assert_eq!(
            identity.chain.len(),
            1,
            "a self-signed signer ships one cert"
        );
        assert!(
            !identity.key_der.is_empty(),
            "the imported key must have bytes; an empty key would fail later at sign time"
        );
        assert!(
            identity.chain[0].starts_with(&[0x30]),
            "a certificate is a DER SEQUENCE, so it must start with 0x30"
        );
        assert!(
            !identity.alias.is_empty(),
            "the alias is how the user picks this identity, so it must survive import"
        );
    }

    #[test]
    fn the_wrong_password_is_reported_as_a_password_problem_not_a_broken_file() {
        // Sending someone after a corrupt download when they fat-fingered the password is the
        // kind of error message this codebase has a rule about.
        let error = import_bytes(SIGNER_PFX, "wrong-horse").expect_err("must refuse");
        assert!(
            matches!(error, AppError::PfxPasswordOrDamaged),
            "a MAC failure must be its own error, got {error:?}"
        );
    }

    #[test]
    fn an_empty_password_does_not_open_a_passworded_archive() {
        let error = import_bytes(SIGNER_PFX, "").expect_err("must refuse");
        assert!(matches!(error, AppError::PfxPasswordOrDamaged));
    }

    #[test]
    fn a_tampered_archive_is_refused_rather_than_partially_imported() {
        // A flipped byte inside the encrypted content makes the MAC disagree. Accepting it would
        // mean shipping a keystore the reader could not authenticate, which is the entire reason
        // PKCS#12 carries a MAC.
        let mut tampered = SIGNER_PFX.to_vec();
        let middle = tampered.len() / 2;
        tampered[middle] ^= 0xff;
        let error = import_bytes(&tampered, SIGNER_PASSWORD).expect_err("must refuse");
        assert!(matches!(error, AppError::PfxPasswordOrDamaged));
    }

    #[test]
    fn a_keystore_with_no_usable_identity_is_refused_rather_than_reported_as_empty() {
        // Exported with `-nocerts`: a shrouded key and no certificate, so `Strict` links nothing
        // and the import reduces to an empty set. Every step succeeds and the user is handed
        // nothing, which is the silent-skip failure this codebase treats as a bug even when the
        // exit status is zero. Refused, with a message that says what is missing.
        let key_only = include_bytes!("../../../tests/fixtures/signing/keyonly.pfx");
        let error = import_bytes(key_only, SIGNER_PASSWORD).expect_err("must not report success");
        let AppError::PfxInvalid(message) = &error else {
            panic!("an empty keystore is not a password problem, got {error:?}");
        };
        assert!(
            message.contains("no private key with a matching certificate"),
            "the message must say what the archive lacks, got {message:?}"
        );
    }

    #[test]
    fn a_file_that_is_not_a_pfx_is_refused_with_its_own_error() {
        // Distinct from the password case: this one is not the user's password, it is the wrong
        // file, and the remedy is different.
        let error =
            import_bytes(b"%PDF-1.7 not a pfx at all", "whatever").expect_err("must refuse");
        assert!(
            matches!(error, AppError::PfxInvalid(_)),
            "a non-PFX must not be reported as a password failure, got {error:?}"
        );
    }

    #[test]
    fn the_password_is_taken_from_the_store_rather_than_a_copy_the_caller_holds() {
        let dir = std::env::temp_dir().join(format!("docreader-pfx-store-{}", std::process::id()));
        std::fs::create_dir_all(&dir).expect("temp dir");
        let path = dir.join("signer.pfx");
        std::fs::write(&path, SIGNER_PFX).expect("write the fixture");

        let store = PasswordStore::new();
        assert!(
            import_with_store(&store, &path)
                .expect("reading the file is not a password failure")
                .is_none(),
            "with no password held the import must report absence, not attempt a guess"
        );

        store.remember(
            &path.to_string_lossy(),
            crate::editor::session::SessionPassword::new(SIGNER_PASSWORD),
        );
        let imported = import_with_store(&store, &path)
            .expect("the store's password opens the archive")
            .expect("a password was held");
        assert_eq!(imported.identities.len(), 1);

        let _ = std::fs::remove_file(&path);
    }

    #[test]
    fn the_imported_identity_never_prints_its_key() {
        let imported = import_bytes(SIGNER_PFX, SIGNER_PASSWORD).expect("opens");
        let rendered = format!("{:?}", imported.identities[0]);
        assert!(rendered.contains("redacted"), "{rendered}");
        let key_fragment = format!("{:?}", imported.identities[0].key_der);
        assert!(
            !rendered.contains(&key_fragment),
            "the Debug output must not contain the key's own rendering"
        );
    }
}
