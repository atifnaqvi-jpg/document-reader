/// The AFM width table for a standard-14 `/BaseFont` name, or `None` for any other font.
///
/// Matching is exact after trimming: the caller has already stripped a subset prefix and
/// normalised the family/style, and a near-miss name (say `HelveticaNeue`) must not be
/// answered with Helvetica's metrics.
pub fn widths_for(base_font: &str) -> Option<&'static [u16; 256]> {
    Some(match base_font.trim() {
        "Helvetica" => &HELVETICA_WIDTHS,
        "Helvetica-Bold" => &HELVETICA_BOLD_WIDTHS,
        "Helvetica-Oblique" => &HELVETICA_OBLIQUE_WIDTHS,
        "Helvetica-BoldOblique" => &HELVETICA_BOLD_OBLIQUE_WIDTHS,
        "Times-Roman" => &TIMES_ROMAN_WIDTHS,
        "Times-Bold" => &TIMES_BOLD_WIDTHS,
        "Times-Italic" => &TIMES_ITALIC_WIDTHS,
        "Times-BoldItalic" => &TIMES_BOLD_ITALIC_WIDTHS,
        "Courier" => &COURIER_WIDTHS,
        "Courier-Bold" => &COURIER_BOLD_WIDTHS,
        "Courier-Oblique" => &COURIER_OBLIQUE_WIDTHS,
        "Courier-BoldOblique" => &COURIER_BOLD_OBLIQUE_WIDTHS,
        _ => return None,
    })
}

/// Encodes `text` to WinAnsi bytes, or `None` when any character has no WinAnsi code.
///
/// This goes through `lopdf`'s own `WinAnsiEncoding`, the same one the product's
/// re-encode step uses, so a byte chosen here is a byte that step will reproduce.
/// `string_to_bytes` silently *drops* an unmappable character, so an encoding is only
/// accepted when it produced exactly one byte per UTF-16 unit of the input — that is what
/// turns a silent drop into a `None` (and, upstream, into `GLYPHS_NOT_COVERABLE`).
pub fn winansi_encode(text: &str) -> Option<Vec<u8>> {
    let encoding = lopdf::Encoding::SimpleEncoding(b"WinAnsiEncoding");
    let bytes = encoding.string_to_bytes(text);
    (bytes.len() == text.encode_utf16().count()).then_some(bytes)
}

/// True when every character of `text` has an AFM width in `base_font`.
///
/// Width 0 means "undefined for this encoding"; it is treated as uncovered rather than as
/// a zero-advance glyph.
pub fn covers(base_font: &str, text: &str) -> bool {
    let Some(widths) = widths_for(base_font) else {
        return false;
    };
    winansi_encode(text).is_some_and(|bytes| bytes.iter().all(|b| widths[*b as usize] != 0))
}

/// The advance width of `text` in `base_font` at `font_size` points, or `None` when the
/// font is not standard-14 or a character cannot be encoded.
///
/// AFM widths are thousandths of an em, so the sum is scaled by `font_size / 1000`.
pub fn text_width(base_font: &str, text: &str, font_size: f32) -> Option<f32> {
    let widths = widths_for(base_font)?;
    let bytes = winansi_encode(text)?;
    let mut thousandths: f64 = 0.0;
    for byte in bytes {
        let width = widths[byte as usize];
        if width == 0 {
            return None;
        }
        thousandths += f64::from(width);
    }
    Some((thousandths * f64::from(font_size) / 1000.0) as f32)
}
