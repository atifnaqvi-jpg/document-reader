//! Standard-14 AFM advance widths (P2.4 Stage 2, MECH-A).
//!
//! The standard-14 fonts need no embedded program and no glyph files: every conformant
//! viewer ships them (ISO 32000-1 9.6.2.2), so a run whose own font is a subset can be
//! edited by *switching* it to a standard-14 font whose glyph coverage is total for
//! Latin-1/WinAnsi. That is MECH-A, and this module is its metric source.
//!
//! Widths are AFM constants in thousandths of an em, indexed by **WinAnsi code** (ISO
//! 32000-1 Annex D). Code 0 is "undefined": the coverage check refuses those before any
//! width is consulted, so a 0 here never becomes a silent zero-width glyph.
//!
//! The tables are generated from the Adobe AFM metrics (reportlab's `pdfmetrics`, which
//! carries the same values as the AFM files); they are pinned here so the shipped binary
//! has no font-file dependency. For standard-14 the numbers *are* the metrics, so no font
//! parsing is involved (T12).

